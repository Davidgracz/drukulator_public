const assert = require('node:assert/strict');
const fs=require('fs');
const vm=require('vm');
const root=require('../data/prices.json');
const context={};context.window=context;
vm.runInNewContext(fs.readFileSync(require('path').join(__dirname,'../js/calculators.js'),'utf8'),context);
const C=context.Calculators;
assert.equal(C.calculateBanner(root,100,100,1,'Baner powlekany 510g').price,80);
assert.equal(C.calculateBanner(root,100,100,1,'Folia + laminat').price,100);
assert.ok(C.calculateBanner(root,135,200,1,'Folia + laminat').price>0);
assert.throws(()=>C.calculateBanner(root,136,200,1,'Folia + laminat'),/135/);
assert.throws(()=>C.calculateBanner(root,200,136,1,'Folia + laminat'),/135/);
assert.ok(C.calculateBanner(root,160,300,1,'Baner powlekany 510g').price>0);
assert.ok(C.calculateBanner(root,300,160,1,'Baner powlekany 510g').price>0);
assert.throws(()=>C.calculateBanner(root,300,161,1,'Baner powlekany 510g'),/160/);
assert.throws(()=>C.calculateBanner(root,20,100,1,'Baner powlekany 510g'),/30/);
assert.equal(C.calculatePosters(root,'Wielkoformatowy 24h','A2',30).price,30*20);
assert.throws(()=>C.calculatePosters(root,'Wielkoformatowy 24h','A2',31),/30/);
assert.throws(()=>C.calculatePosters(root,'Wielkoformatowy 24h','A2',101),/30/);
assert.ok(C.calculateFoamBoardCustom(root,'Plansza pianka 5 mm',50,50,1).price>0);
assert.ok(C.calculatePvc(root,50,50,1,'Folia z nadrukiem + PCV','4/5 mm').price>0);
console.log('OK: banners orientations, laminate width, posters 1-30, PVC/foam pricing');
